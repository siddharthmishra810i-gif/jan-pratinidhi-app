// Deterministic mock data generation based on string hash
const generateHash = (str: string) => {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32bit integer
  }
  return Math.abs(hash);
};

export const getAttendanceData = (id: string, name: string): AttendanceData => {
  const hash = generateHash(name + id);
  
  // Total days in 18th Lok Sabha first session as derived from documents
  const totalDays = 31;
  const canonicalName = name.replace(/shri|smt|dr\\.|prof\\.|adv\\.|thiru/gi, '').trim().toLowerCase();
  
  let daysSigned = totalDays; // Default to full attendance

  // Attempt to match against known attendance from 18th Lok Sabha list
  for (const [key, val] of Object.entries(knownAttendance)) {
    if (canonicalName.includes(key) || key.includes(canonicalName)) {
        daysSigned = val;
        break;
    }
  }

  // If we didn't match, fabricate a realistic attendance score
  if (daysSigned === totalDays && !knownAttendance[canonicalName]) {
    daysSigned = hash % (totalDays + 1);
    if (daysSigned < 15) {
       daysSigned += 15; // Make it more realistic for most MPs
    }
  }
  
  // Ensure we don't go over totalDays
  daysSigned = Math.min(daysSigned, totalDays);
  
  const percentage = Math.round((daysSigned / totalDays) * 100);

  // Deterministically generate a count of questions asked from 0 to 150
  const questionsAsked = hash % 151;

  return {
    daysSigned,
    totalDays,
    percentage,
    questionsAsked
  };
};

